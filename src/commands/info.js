/**
 * Builds rows for the project metadata display box.
 *
 * @param {object} project
 * @param {string[]} files
 * @returns {string[]}
 */
function buildProjectRows(project, files) {
  const permissionText =
    project.permission === "both"
      ? pc.green("Read & Write (both)")
      : project.permission === "write"
        ? pc.yellow("Write-only")
        : pc.cyan("Read-only");

  const approvalText = isApprovalRequired(project, "WRITE")
    ? pc.yellow("Enabled (Ask before changes)")
    : pc.dim("Disabled (Auto-apply)");

  return [
    `${pc.bold("Name        :")} ${pc.green(project.name)} ${pc.dim(`(${project.id})`)}`,
    `${pc.bold("Root        :")} ${pc.dim(project.root)}`,
    `${pc.bold("Config      :")} ${
      project.configFile
        ? pc.green(path.basename(project.configFile))
        : pc.yellow("(none - using default)")
    }`,
    `${pc.bold("Description :")} ${project.description || pc.dim("(none)")}`,
    `${pc.bold("Permission  :")} ${permissionText}`,
    `${pc.bold("Approval    :")} ${approvalText}`,
    `${pc.bold("Context File:")} ${project.contextFile ? pc.green(project.contextFile) : pc.dim("(none)")}`,
    `${pc.bold("Files       :")} ${pc.cyan(String(files.length))} source files indexed`,
  ];
}

/**
 * Builds rows for the session and authentication display box.
 *
 * @param {object} project
 * @param {string} passwordType
 * @param {number|string} port
 * @param {boolean} daemonRunning
 * @param {object|null} daemonState
 * @returns {string[]}
 */
function buildSessionRows(project, passwordType, port, daemonRunning, daemonState) {
  const daemonText = daemonRunning
    ? `${pc.green(`Active (PID: ${daemonState.pid}, Port: ${port})`)}`
    : `${pc.yellow("Inactive")} ${pc.dim("(run 'codemcp -d' to run in background)")}`;

  const clientCount = clientStore ? clientStore.size : 0;
  let clientsText = pc.dim("None registered yet");
  if (clientCount > 0) {
    const distinctNames = [
      ...new Set(
        [...clientStore.values()]
          .map((c) => c.client_name || c.client_id)
          .filter(Boolean),
      ),
    ];
    const preview = distinctNames.slice(0, 2).join(", ");
    const extra = distinctNames.length > 2 ? `, +${distinctNames.length - 2} more` : "";
    clientsText = `${pc.cyan(String(clientCount))} ${pc.dim(`(${preview}${extra})`)}`;
  }

  let browserSessions = [];
  try {
    browserSessions = listSessions() || [];
  } catch {}
  const browserText =
    browserSessions.length > 0
      ? `${pc.cyan(String(browserSessions.length))} active`
      : pc.dim("0 active sessions");

  const tokenExpiry = process.env.TOKEN_EXPIRY_SECONDS || "86400";
  let credCount = 0;
  try {
    credCount = Object.keys(getAllCredentials() || {}).length;
  } catch {}

  const rows = [
    `${pc.bold("Project      :")} ${pc.green(project.name)} ${pc.dim(`(${project.id})`)}`,
    `${pc.bold("Password     :")} ${passwordType}`,
    `${pc.bold("Local URL    :")} ${pc.cyan(`http://localhost:${port}/mcp`)}`,
    `${pc.bold("Daemon       :")} ${daemonText}`,
  ];

  if (daemonRunning && daemonState?.startedAt) {
    const elapsedSec = Math.floor((Date.now() - daemonState.startedAt) / 1000);
    const uptimeStr =
      elapsedSec < 60
        ? `${elapsedSec}s`
        : elapsedSec < 3600
          ? `${Math.floor(elapsedSec / 60)}m ${elapsedSec % 60}s`
          : `${Math.floor(elapsedSec / 3600)}h ${Math.floor((elapsedSec % 3600) / 60)}m`;
    rows.push(`${pc.bold("Uptime       :")} ${pc.dim(uptimeStr)}`);
    rows.push(
      `${pc.bold("Log File     :")} ${pc.dim(daemonState.logFile || getDaemonLogPath(project.root))}`,
    );
  }

  rows.push(
    `${pc.bold("Token Life   :")} ${pc.white(`${tokenExpiry}s`)} ${pc.dim(`(${Math.round(parseInt(tokenExpiry, 10) / 3600)}h)`)}`,
  );
  rows.push(`${pc.bold("OAuth Clients:")} ${clientsText}`);
  rows.push(`${pc.bold("Browser Ssns :")} ${browserText}`);
  rows.push(
    `${pc.bold("Vault File   :")} ${pc.dim("~/.codemcp/credentials.enc")} ${pc.dim(`(${credCount} stored)`)}`,
  );

  return rows;
}

/**
 * Displays project metadata, source file count, and session/auth information.
 *
 * @param {string} targetDir
 * @param {object} [options={}]
 * @param {boolean} [options.session] - Show session/daemon and authentication info
 * @param {boolean} [options.password] - Output only the owner authentication password
 * @param {boolean} [options.all] - Show both project metadata and session info
 */
export function infoProject(targetDir = process.cwd(), options = {}) {
  const project = findProjectConfig(targetDir);

  const passwordVal = getOwnerPassword();
  const isAuto = isAutoGeneratedPassword();
  const passwordType = isAuto
    ? `${pc.bold(pc.yellow(passwordVal))} ${pc.dim("(auto-generated, saved to vault)")}`
    : `${pc.bold(pc.green(passwordVal))} ${pc.dim("(configured via OWNER_PASSWORD)")}`;

  // If user requested password only (-p / --password)
  if (options.password) {
    console.log(`\n  ${pc.bold("Owner Password :")} ${passwordType}\n`);
    return { project, password: passwordVal, isAuto };
  }

  const showSession = Boolean(options.session || options.all);
  const showProject = !options.session || Boolean(options.all);

  let files = [];
  if (showProject) {
    try {
      walk(project.root, "", files, project.root);
    } catch (err) {
      console.warn(
        pc.yellow(
          `[info] Warning: Could not list files in ${project.root}: ${err.message}`,
        ),
      );
    }

    const title = pc.bold(pc.bgCyan(pc.black(" CodeMCP - Project Info ")));
    const rows = buildProjectRows(project, files);
    printBox(title, rows);
  }

  let daemonRunning = false;
  let daemonState = null;

  if (showSession) {
    daemonState = readDaemonState(project.root);
    daemonRunning = Boolean(
      daemonState?.pid && isProcessRunning(daemonState.pid),
    );
    const port = (daemonRunning ? daemonState?.port : process.env.PORT) ?? 4173;

    const sessionTitle = pc.bold(
      pc.bgMagenta(pc.black(" CodeMCP - Session & Auth Info ")),
    );
    const sessionRows = buildSessionRows(
      project,
      passwordType,
      port,
      daemonRunning,
      daemonState,
    );
    printBox(sessionTitle, sessionRows, { color: pc.magenta });
  }

  if (!showSession && !options.password) {
    console.log(
      pc.dim(
        "  Tip: Run 'codemcp info -s' to view active session, connection URLs, and password.\n",
      ),
    );
  } else {
    console.log();
  }

  return { project, files, daemonRunning, password: passwordVal };
}
